/**
 * Mutation testing configuration.
 *
 * WHY THIS EXISTS
 *
 * This repo has an unusually mature anti-decorative-test culture. It has
 * `TEST_AUDIT.md`, AGENTS.md Testing Standards rules 1/3/4/8/9 (never
 * re-implement a function's logic in a test, no vacuous branches, every feature
 * needs a negative test, no overclaiming comments, tests must import the code
 * under test), and an entire spec — `specs/test-honesty.spec.md` — devoted to
 * "remove the tests that cannot fail".
 *
 * Every instance of that defect class was found by **a human reading tests**.
 * `c339b04 test: remove the tests that cannot fail` came from reading, not from
 * the suite. That process does not scale and does not repeat: it depends on
 * someone choosing to audit, and it silently stops the moment nobody does.
 *
 * Stryker closes the loop mechanically. It mutates the source — flips `>` to
 * `>=`, removes a branch, replaces a string — and reports which mutants SURVIVED.
 * A surviving mutant is a behaviour the tests claim to cover and do not. That is
 * rule 1 and rule 4 violations, found by running something.
 *
 * SCOPE
 *
 * Deliberately NOT the whole tree. Mutation testing the React components would
 * mean rendering them in tests, which is a different (and much larger) project,
 * and would produce thousands of surviving mutants nobody would act on.
 *
 * The scope is the pure-logic core — exactly the modules `vitest.config.ts`
 * already holds to 85–95% coverage. Those are the modules where a logic error is
 * both likely and costly (date maths, import parsing, export serialisation,
 * placeholder substitution, storage quota projection), and where a test that
 * does not actually assert is easiest to write without noticing.
 *
 * The threshold is a ratchet like the coverage numbers: high enough to catch a
 * genuinely untested branch, low enough to be reachable in a normal session.
 */

/**
 * Stryker 10 no longer exports `defineConfig` from `@stryker-mutator/core`
 * (the exports are `Stryker`, `StrykerCli`, `default`). A plain default export
 * is the supported config shape, and `Config` is a type-only import — types are
 * erased at runtime, so it is safe in an ESM config file.
 *
 * @type {import('@stryker-mutator/api/core').Config}
 */

/**
 * The pure-logic core.
 *
 * Selected for three reasons: it is the code with the highest cost-of-error
 * (silent data corruption in exports, wrong dates, quota miscalculation), it is
 * already under per-module coverage thresholds, and it contains no DOM
 * dependency, so mutation runs fast and the results are trustworthy.
 */
const CORE = [
  "src/utils/dateUtils.ts",
  "src/utils/usageTracking.ts",
  "src/types/index.ts",
  "src/lib/markdown.ts",
  "src/lib/content-helpers.ts",
  "src/lib/sentry-scrub.ts",
  "src/lib/exporters/clipio.ts",
  "src/lib/importers/clipio.ts",
  "src/lib/importers/detect.ts",
  "src/lib/importers/powertext.ts",
  "src/lib/importers/textblaze.ts",
  "src/lib/update-checker.ts",
  "src/lib/review-prompt.ts",
  "src/components/editor/serialization.ts",
  "src/storage/normalize.ts",
  "src/storage/types.ts",
  "src/storage/quota-preflight.ts",
];

export default {
  /**
   * Plugins must be named explicitly in Stryker 10. It used to auto-load every
   * `@stryker-mutator/*` package found next to the CLI; without this the run
   * dies at startup with:
   *
   *     Cannot find TestRunner plugin "vitest". In fact, no TestRunner plugins
   *     were loaded. Did you forget to install it?
   */
  plugins: ["@stryker-mutator/vitest-runner"],

  /**
   * Run mutants IN PLACE rather than in a sandbox.
   *
   * The sandbox approach does not work in this repo, and the reason is worth
   * recording so nobody "optimises" it back:
   *
   * Stryker builds its sandbox by copying files while respecting `.gitignore`.
   * The repo's `.wxt/` directory is gitignored (correctly — regenerated by
   * `wxt prepare` on every install), so it was never copied. But `tsconfig.json`
   * — which IS copied — opens with `"extends": "./.wxt/tsconfig.json"`, and
   * Vite resolves tsconfig `extends` per-file from the file being transformed.
   * Every source file in the sandbox therefore failed to resolve the extends,
   * and **all 54 test suites failed to load before a single mutant was
   * generated**.
   *
   * The alternatives were worse: un-ignoring `.wxt/` would put seven generated
   * build artifacts under version control, and pointing Vitest at a different
   * tsconfig does not work because Vitest resolves the *nearest* tsconfig for
   * each file, and the copied `tsconfig.json` sits in the sandbox root where it
   * wins.
   *
   * `inPlace` sidesteps the whole problem: mutants are written to the real
   * working tree, where `.wxt/` is present exactly as for every other command.
   * Stryker restores the original file afterwards, so the tree is left clean.
   * It is also faster, since nothing is copied.
   *
   * The one caveat: an interrupted run can leave a mutated file behind. If a run
   * is killed, `git status` will show modified source files — check them out
   * before continuing.
   */
  inPlace: true,
  testRunner: "vitest",
  packageManager: "pnpm",
  reporters: ["html", "clear-text", "progress"],

  mutate: CORE,

  // ── Mutators ───────────────────────────────────────────────────────────
  // Stryker's built-in mutator set is used unchanged. Every mutation here
  // corresponds to a plausible mistake in this codebase: flipping a comparison,
  // removing a null guard, negating a boolean, changing a string constant.
  // Custom mutators were considered and rejected — a bespoke mutator only pays
  // off if it catches something the standard set provably misses, and adding
  // unmeasured ones would make the score harder to interpret, not easier.

  // ── Where the survivors land ───────────────────────────────────────────
  htmlReporter: {
    fileName: "reports/mutation/index.html",
  },
  jsonReporter: {
    fileName: "reports/mutation/mutation.json",
  },

  // ── Thresholds ────────────────────────────────────────────────────────
  //
  // A ratchet, like the coverage numbers in vitest.config.ts. High enough that
  // a genuinely untested branch fails; low enough to be reachable.
  thresholds: {
    // 80% of mutants killed means the test suite genuinely pins the behaviour
    // of these modules, rather than merely exercising their lines.
    high: 80,
    // 60% is the floor for "still worth running". Below this the suite is not
    // really testing this code and the number stops being informative.
    low: 60,
    break: null,
  },

  // ── Runtime ───────────────────────────────────────────────────────────
  //
  // `related: true` (the default) runs only the tests that import the mutated
  // file. That is what keeps a mutation run tractable: for `markdown.ts` it is
  // the handful of suites that touch it, not all 54.
  //
  // The Stryker 10 schema accepts only `dir`, `related` and `configFile` here.
  // Earlier versions took `pool`, `poolOptions` and `tsconfigFile`, and passing
  // them is a hard validation error rather than a warning:
  //
  //     Config option "vitest" must NOT have additional properties
  vitest: {
    configFile: "vitest.config.ts",
    related: true,
  },

  // Coverage instrumentation is meaningless here and slows every worker down.
  coverageAnalysis: "off",

  // ── Concurrency ───────────────────────────────────────────────────────
  // Half the cores: these are the heaviest tests in the repo, and saturating
  // the machine makes the run take longer than it saves.
  concurrency: "50%",

  // ── Timeouts ──────────────────────────────────────────────────────────
  // Each worker runs the full vitest suite once per mutant batch. A slow test
  // should fail loudly rather than hang a mutation run for an hour.
  timeoutMS: 120_000,
  timeoutFactor: 2,
  maxTestRunnerReuse: 20,

  // ── Output hygiene ────────────────────────────────────────────────────
  // Keep reports out of the coverage and playwright output trees so the
  // integrity gate and the artifact uploads stay unambiguous.
  tempDirName: ".stryker-tmp",
};
