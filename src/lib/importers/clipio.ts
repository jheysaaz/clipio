/**
 * Parse a Clipio v2 ZIP file.
 *
 * Extracts `export.json` and all `media/<id>.<ext>` blobs.
 * Returns parsed snippets, restored media blobs, and a list of missing IDs.
 *
 * Throws if the ZIP is unreadable or `export.json` is malformed.
 */
/**
 * Upper bound on the total *inflated* bytes a Clipio ZIP may produce.
 *
 * `unzipSync` inflates the whole archive before any per-entry validation runs,
 * so without a budget a 42-byte ZIP can exhaust memory in the options page.
 * The budget is derived from MEDIA_LIMITS.MAX_TOTAL_SIZE so the archive limit
 * and the store limit cannot drift apart, plus headroom for export.json — a
 * user at the media cap produces media of exactly MAX_TOTAL_SIZE, and the
 * manifest is on top of it. Without the headroom such a user cannot restore
 * their own backup.
 * spec: specs/media-import-hardening.spec.md
 */
/** Headroom for export.json, which is not media and is not quota-bound. */
export const MAX_MANIFEST_INFLATED_BYTES = 8 * 1024 * 1024;

export const MAX_ZIP_INFLATED_BYTES =
  MEDIA_LIMITS.MAX_TOTAL_SIZE + MAX_MANIFEST_INFLATED_BYTES;

/**
 * Media IDs are produced by crypto.randomUUID() and are interpolated into
 * `{{image:<id>}}` placeholders and used to build the archive path
 * (`media/${id}.`), so an id is only accepted if it is a short, opaque token.
 *
 * The check is deliberately a conservative charset rather than a strict UUID
 * match. A strict match would reject any export whose ids were generated by a
 * different scheme, and a user restoring their own backup is not an attack.
 * What actually matters is that an id cannot contain a path separator, a dot,
 * or the brace/colon characters that would let it escape into a placeholder.
 *
 * spec: specs/media-import-hardening.spec.md
 */
const MEDIA_ID_PATTERN = /^[A-Za-z0-9_-]{1,64}$/;

export function isValidMediaId(id: unknown): boolean {
  return typeof id === "string" && MEDIA_ID_PATTERN.test(id);
}

export async function importClipioZip(
  file: File
): Promise<ClipioZipImportResult> {
  const arrayBuffer = await file.arrayBuffer();

  // fflate's filter callback receives UnzipFileInfo, whose `originalSize` is
  // the inflated size, available BEFORE extraction. That lets us refuse a
  // decompression bomb without first allocating gigabytes.
  let declaredInflated = 0;
  const unzipped = unzipSync(new Uint8Array(arrayBuffer), {
    filter: (info) => {
      declaredInflated += info.originalSize;
      if (declaredInflated > MAX_ZIP_INFLATED_BYTES) {
        throw new Error(
          `Invalid Clipio ZIP: archive inflates to more than ${MAX_ZIP_INFLATED_BYTES} bytes`
        );
      }
      return true;
    },
  });

  const jsonBytes = unzipped["export.json"];
  if (!jsonBytes) {
    throw new Error("Invalid Clipio ZIP: missing export.json");
  }

  const json = new TextDecoder().decode(jsonBytes);
  let envelope: ClipioEnvelope;
  try {
    envelope = JSON.parse(json) as ClipioEnvelope;
  } catch {
    throw new Error("Invalid Clipio ZIP: export.json is not valid JSON");
  }

  if (envelope.format !== "clipio") {
    throw new Error("Invalid Clipio ZIP: export.json is not a Clipio export");
  }

  const snippets = (envelope.snippets ?? []).filter(isValidSnippet);
  const parsedSnippets = snippets.map(snippetToParsed);

  const mediaBlobs = new Map<string, { blob: Blob; meta: MediaMetadata }>();
  const missingMediaIds: string[] = [];

  const mediaMeta = envelope.media ?? [];

  for (const meta of mediaMeta) {
    // Reject ids that are not safe opaque tokens, but report them as missing
    // rather than dropping them silently, so the import wizard can tell the
    // user which media did not come across.
    if (!isValidMediaId(meta.id)) {
      missingMediaIds.push(String(meta.id));
      continue;
    }
    // Look for a matching file in the media/ directory
    const prefix = `media/${meta.id}.`;
    const entry = Object.keys(unzipped).find((k) => k.startsWith(prefix));

    if (entry) {
      const mimeType = meta.mimeType || guessMimeFromPath(entry);
      const blob = new Blob([unzipped[entry].buffer as ArrayBuffer], {
        type: mimeType,
      });
      mediaBlobs.set(meta.id, { blob, meta });
    } else {
      missingMediaIds.push(meta.id);
    }
  }

  return { snippets: parsedSnippets, mediaBlobs, missingMediaIds };
}

function guessMimeFromPath(path: string): string {
  if (path.endsWith(".webp")) return "image/webp";
  if (path.endsWith(".jpg") || path.endsWith(".jpeg")) return "image/jpeg";
  if (path.endsWith(".gif")) return "image/gif";
  return "image/png";
}
