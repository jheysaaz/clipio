/**
 * Clipio import parser — supports both formats:
 *  1. Legacy bare array:   [ { id, label, shortcut, content, ... }, ... ]
 *  2. Versioned envelope:  { version: 1, format: "clipio", exportedAt, snippets: [...] }
 *  3. ZIP envelope (v2):   ZIP file containing export.json + media/ blobs
 */

import type { ParsedSnippet, FormatParser } from "./types";
import type { Snippet } from "@/types";
import type { MediaMetadata } from "@/storage/backends/media";
import { unzipSync } from "fflate";
import { isValidImportedSnippet } from "@/lib/snippet-schema";
import { migrateContentFormat } from "@/lib/content-format-migration";
import { MEDIA_LIMITS } from "@/config/constants";

interface ClipioEnvelope {
  version: number;
  format: "clipio";
  exportedAt?: string;
  snippets: Snippet[];
  media?: MediaMetadata[];
}

export interface ClipioZipImportResult {
  snippets: ParsedSnippet[];
  /** Restored media blobs keyed by their ID from the export. */
  mediaBlobs: Map<string, { blob: Blob; meta: MediaMetadata }>;
  /** IDs of media entries referenced in snippets but missing from the ZIP. */
  missingMediaIds: string[];
}

/**
 * Validation lives in src/lib/snippet-schema.ts, shared with the storage-level
 * import path. A second, weaker copy here is exactly how the two drifted
 * apart: this one never checked bounds, timestamps, tags, or prototype keys.
 */
const isValidSnippet = isValidImportedSnippet;

function snippetToParsed(raw: Snippet): ParsedSnippet {
  // This function, not the shared validator, is what turns a Clipio record into
  // a snippet: `parse` filters with a boolean predicate and then maps the RAW
  // records, so nothing downstream has normalised them. A 1.x record carrying
  // `contentFormat: "html"` therefore has to be converted right here — the flag
  // is the only record that the body is HTML, and once it is dropped the body
  // is treated as markdown for good and inserts as visible escaped text.
  //
  // Both Clipio entry points (the JSON file and the v2 ZIP) funnel through
  // here, so one call covers both. spec: specs/content-format-migration.spec.md
  const snippet = migrateContentFormat(raw);
  return {
    suggestedId: snippet.id,
    label: snippet.label,
    shortcut: snippet.shortcut,
    content: snippet.content,
    tags: snippet.tags ?? [],
    // Clipio snippets are already in our format — no unsupported placeholders
    unsupportedPlaceholders: [],
  };
}

export const ClipioParser: FormatParser = {
  id: "clipio",
  displayName: "Clipio",
  iconUrl: "/icon/128.png",

  canParse(raw: unknown): boolean {
    if (raw === null || typeof raw !== "object") return false;

    // Versioned envelope
    if (
      !Array.isArray(raw) &&
      (raw as Record<string, unknown>)["format"] === "clipio"
    ) {
      return true;
    }

    // Legacy bare array
    if (Array.isArray(raw)) {
      if (raw.length === 0) return true;
      return isValidSnippet(raw[0]);
    }

    return false;
  },

  parse(raw: unknown): ParsedSnippet[] {
    let snippets: Snippet[];

    if (Array.isArray(raw)) {
      snippets = (raw as unknown[]).filter(isValidSnippet);
    } else {
      const envelope = raw as ClipioEnvelope;
      snippets = (envelope.snippets ?? []).filter(isValidSnippet);
    }

    return snippets.map(snippetToParsed);
  },
};

